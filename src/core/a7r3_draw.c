void a7r3_draw_text_ascii(uint16_t *canvas, int x, int y, const char *s,
                          uint16_t color, int scale)
{
    int cx = x;
    int col, row;
    if (!canvas || !s)
        return;
    if (scale < 1)
        scale = 1;
    while (*s) {
        unsigned ch = (unsigned char)*s++;
        if (ch < 0x20u || ch > 0x7eu)
            ch = '?';
        const uint8_t *g = g_font5x7[ch - 0x20u];
        for (col = 0; col < 5; col++) {
            uint8_t bits = g[col];
            for (row = 0; row < 7; row++) {
                if (bits & (1u << row))
                    a7r3_draw_fill_rect(canvas, cx + col * scale, y + row * scale,
                                        scale, scale, color);
            }
        }
        cx += 6 * scale;
    }
}
