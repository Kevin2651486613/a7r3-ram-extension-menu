void a7r3_draw_clear(uint16_t *canvas, uint16_t color)
{
    unsigned i;
    if (!canvas)
        return;
    for (i = 0; i < A7R3_FB_PIXELS; i++)
        canvas[i] = color;
}

static void clip_rect(int *x, int *y, int *w, int *h)
{
    int x0 = *x, y0 = *y;
    int x1 = x0 + *w, y1 = y0 + *h;
    if (x0 < 0) x0 = 0;
    if (y0 < 0) y0 = 0;
    if (x1 > (int)A7R3_FB_W) x1 = (int)A7R3_FB_W;
    if (y1 > (int)A7R3_FB_H) y1 = (int)A7R3_FB_H;
    *x = x0;
    *y = y0;
    *w = (x1 > x0) ? (x1 - x0) : 0;
    *h = (y1 > y0) ? (y1 - y0) : 0;
}

void a7r3_draw_fill_rect(uint16_t *canvas, int x, int y, int w, int h, uint16_t color)
{
    int px, py;
    if (!canvas)
        return;
    clip_rect(&x, &y, &w, &h);
    for (py = y; py < y + h; py++) {
        uint16_t *row = canvas + (unsigned)py * A7R3_FB_W + (unsigned)x;
        for (px = 0; px < w; px++)
            row[px] = color;
    }
}

void a7r3_draw_stroke_rect(uint16_t *canvas, int x, int y, int w, int h, int thickness, uint16_t color)
{
    if (!canvas || w <= 0 || h <= 0 || thickness <= 0)
        return;
    a7r3_draw_fill_rect(canvas, x, y, w, thickness, color);
    a7r3_draw_fill_rect(canvas, x, y + h - thickness, w, thickness, color);
    a7r3_draw_fill_rect(canvas, x, y, thickness, h, color);
    a7r3_draw_fill_rect(canvas, x + w - thickness, y, thickness, h, color);
}

void a7r3_draw_dim_rect(uint16_t *canvas, int x, int y, int w, int h)
{
    int px, py;
    if (!canvas)
        return;
    clip_rect(&x, &y, &w, &h);
    for (py = y; py < y + h; py++) {
        uint16_t *row = canvas + (unsigned)py * A7R3_FB_W + (unsigned)x;
        for (px = 0; px < w; px++)
            row[px] = (uint16_t)(((row[px] >> 1) & 0x7777u) | 0x000fu);
    }
}

void a7r3_draw_blit_sprite(uint16_t *canvas, int dx, int dy, int w, int h, const uint16_t *rgba4444)
{
    int x, y;
    if (!canvas || !rgba4444 || w <= 0 || h <= 0)
        return;
    for (y = 0; y < h; y++) {
        int cy = dy + y;
        if (cy < 0 || cy >= (int)A7R3_FB_H)
            continue;
        for (x = 0; x < w; x++) {
            int cx = dx + x;
            uint16_t sp;
            unsigned a;
            if (cx < 0 || cx >= (int)A7R3_FB_W)
                continue;
            sp = rgba4444[y * w + x];
            a = sp & 0xfu;
            if (a == 0u)
                continue;
            if (a == 0xfu) {
                canvas[(unsigned)cy * A7R3_FB_W + (unsigned)cx] = sp;
            } else {
                uint16_t bg = canvas[(unsigned)cy * A7R3_FB_W + (unsigned)cx];
                unsigned inv = 15u - a;
                unsigned r = (((sp >> 12) & 0xfu) * a + ((bg >> 12) & 0xfu) * inv + 7u) / 15u;
                unsigned g = (((sp >> 8) & 0xfu) * a + ((bg >> 8) & 0xfu) * inv + 7u) / 15u;
                unsigned b = (((sp >> 4) & 0xfu) * a + ((bg >> 4) & 0xfu) * inv + 7u) / 15u;
                canvas[(unsigned)cy * A7R3_FB_W + (unsigned)cx] = A7R3_RGBA4444(r, g, b, 0xfu);
            }
        }
    }
}

void a7r3_draw_alpha4(uint16_t *canvas, int dx, int dy, int w, int h,
                      const uint8_t *alpha4, uint16_t fg)
{
    unsigned fr = (fg >> 12) & 0xfu;
    unsigned fg_c = (fg >> 8) & 0xfu;
    unsigned fb = (fg >> 4) & 0xfu;
    int x, y;

    if (!canvas || !alpha4 || w <= 0 || h <= 0)
        return;
    for (y = 0; y < h; y++) {
        int cy = dy + y;
        if (cy < 0 || cy >= (int)A7R3_FB_H)
            continue;
        for (x = 0; x < w; x++) {
            int cx = dx + x;
            unsigned a;
            if (cx < 0 || cx >= (int)A7R3_FB_W)
                continue;
            a = alpha4[y * w + x] & 0xfu;
            if (a == 0u)
                continue;
            if (a == 0xfu) {
                canvas[(unsigned)cy * A7R3_FB_W + (unsigned)cx] = fg | 0x000fu;
            } else {
                uint16_t bg = canvas[(unsigned)cy * A7R3_FB_W + (unsigned)cx];
                unsigned inv = 15u - a;
                unsigned r = (fr * a + ((bg >> 12) & 0xfu) * inv + 7u) / 15u;
                unsigned g = (fg_c * a + ((bg >> 8) & 0xfu) * inv + 7u) / 15u;
                unsigned b = (fb * a + ((bg >> 4) & 0xfu) * inv + 7u) / 15u;
                canvas[(unsigned)cy * A7R3_FB_W + (unsigned)cx] = A7R3_RGBA4444(r, g, b, 0xfu);
            }
        }
    }
}

